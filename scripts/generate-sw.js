// Build-time service worker: precache every file Vite emitted. Hand-maintained
// SHELL lists previously drifted (capabilities.js was missing) and broke cold
// offline startup, so the list is derived from dist/ on every build.
import { readdirSync, statSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';

const dist = path.resolve('dist');
const files = [];
const walk = (dir) => {
  for (const entry of readdirSync(dir)) {
    const file = path.join(dir, entry);
    if (statSync(file).isDirectory()) walk(file);
    else files.push('/' + path.relative(dist, file).split(path.sep).join('/'));
  }
};
walk(dist);
const shell = ['/', ...files.filter((file) => file !== '/sw.js').sort()];
const version = createHash('sha256').update(JSON.stringify(shell)).digest('hex').slice(0, 10);

const sw = `// Generated by scripts/generate-sw.js — do not edit by hand.
const CACHE = 'nanocore-live-${version}';
const SHELL = ${JSON.stringify(shell, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(Promise.all([
    caches.keys().then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key)))),
    self.clients.claim(),
  ]));
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith((async () => {
    try {
      const response = await fetch(request);
      if (response.ok) {
        const cache = await caches.open(CACHE);
        cache.put(request, response.clone());
      }
      return response;
    } catch (error) {
      const cached = await caches.match(request, { ignoreSearch: true });
      if (cached) return cached;
      if (request.mode === 'navigate') return caches.match('/index.html');
      throw error;
    }
  })());
});
`;
writeFileSync(path.join(dist, 'sw.js'), sw);
console.log(`Generated dist/sw.js: ${shell.length} cached URLs (nanocore-live-${version})`);
